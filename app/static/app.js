function field(id) {
  return document.querySelector(`#${id}`);
}

function localJobTimestamp(date = new Date()) {
  const pad = (value) => String(value).padStart(2, "0");
  return [
    date.getFullYear(),
    pad(date.getMonth() + 1),
    pad(date.getDate())
  ].join("") + "_" + [
    pad(date.getHours()),
    pad(date.getMinutes()),
    pad(date.getSeconds())
  ].join("");
}

function sanitizeJobSku(value) {
  return String(value || "").trim().toUpperCase().replace(/[^A-Z0-9_-]+/g, "");
}

function autoJobIdPrefix() {
  if (field("job-type").value === "group") {
    return "GROUP";
  }
  const enteredSku = normalizeSkuForCompare(field("sku-input").value);
  const lookupSku = lastLookup && normalizeSkuForCompare(lastLookup.sku);
  if (lastLookup && lastLookup.known && enteredSku && enteredSku === lookupSku) {
    return sanitizeJobSku(lastLookup.sku) || "SINGLE";
  }
  return "SINGLE";
}

function refreshAutoJobId({force = false} = {}) {
  const jobIdField = field("job-id");
  if (!force && jobIdField.value.trim() && !jobIdIsAutoGenerated) {
    return;
  }
  jobIdField.value = `${autoJobIdPrefix()}_${localJobTimestamp()}`;
  jobIdIsAutoGenerated = true;
}

function jobSetupItems() {
  if (items.length) {
    return items.map((item) => ({sku: item.sku, quantity: item.quantity}));
  }
  const draftSku = field("sku-input").value.trim();
  if (field("job-type").value === "single" && draftSku) {
    return [{sku: draftSku, quantity: 1}];
  }
  return [];
}

async function postJson(url, payload) {
  const response = await fetch(url, {
    method: "POST",
    headers: {"Content-Type": "application/json"},
    body: JSON.stringify(payload)
  });
  const text = await response.text();
  let data = {};
  try {
    data = text ? JSON.parse(text) : {};
  } catch (error) {
    data = {ok: false, error: "Response was not valid JSON.", details: text};
  }
  if (!response.ok) {
    throw {
      ok: false,
      http_status: response.status,
      http_status_text: response.statusText,
      error: data.error || "Request failed.",
      stage: data.stage,
      details: data.details,
      response: data,
      request_payload: payload,
      url
    };
  }
  return data;
}

function showStatus(data, label = "Response received") {
  outputStatus.textContent = label;
  output.classList.remove("error");
  output.textContent = JSON.stringify(data, null, 2);
  renderResultSummary(data, label);
}

function showError(error, label = "Error") {
  outputStatus.textContent = label;
  output.classList.add("error");
  output.textContent = JSON.stringify(error, null, 2);
  renderResultSummary(error, label, true);
}

function resultValue(value, fallback = "—") {
  if (value === null || value === undefined || value === "") {
    return fallback;
  }
  if (typeof value === "boolean") {
    return value ? "yes" : "no";
  }
  if (Array.isArray(value)) {
    return value.length ? value.join(", ") : "none";
  }
  return String(value);
}

function addSummaryRow(container, label, value, badgeClass = "") {
  const row = document.createElement("div");
  row.className = "result-row";

  const key = document.createElement("span");
  key.className = "result-key";
  key.textContent = label;
  row.appendChild(key);

  const val = document.createElement("span");
  val.className = badgeClass ? `result-value result-badge ${badgeClass}` : "result-value";
  val.textContent = resultValue(value);
  row.appendChild(val);
  container.appendChild(row);
}

function metadataCommonName(metadata) {
  if (!metadata || typeof metadata !== "object") {
    return null;
  }
  return metadata.common_name || metadata.name || metadata.display_name || metadata.description || null;
}

function potPriorLabel(metadata) {
  const prior = metadata && (metadata.pot_prior || metadata);
  if (!prior || !(prior.pot_prior_available || prior.available)) {
    return "none";
  }
  const dims = [];
  if (prior.shape) {
    dims.push(prior.shape);
  }
  if (prior.diameter_in) {
    dims.push(`diameter ${prior.diameter_in} in`);
  }
  if (prior.width_in || prior.depth_in) {
    dims.push(`width/depth ${prior.width_in || "unknown"} x ${prior.depth_in || "unknown"} in`);
  }
  dims.push(prior.height_in ? `height ${prior.height_in} in` : "height unknown");
  return `${dims.join(", ")} (${prior.confidence || "unknown"})`;
}

function firstItemFromPayload(data) {
  if (Array.isArray(data.items) && data.items.length > 0) {
    return data.items[0];
  }
  const resultItems = data.result && data.result.items;
  if (Array.isArray(resultItems) && resultItems.length > 0) {
    return resultItems[0];
  }
  return null;
}

function summaryBadgeForStatus(value) {
  const normalized = String(value || "").toLowerCase();
  if (["ok", "pass", "proceed", "known", "complete", "true", "yes"].includes(normalized)) {
    return "pass";
  }
  if (["fail", "failed", "recapture", "false", "no", "unknown"].includes(normalized)) {
    return "fail";
  }
  return "warn";
}

function renderResultSummary(data, label, isError = false) {
  outputSummary.textContent = "";
  const grid = document.createElement("div");
  grid.className = "result-grid";

  addSummaryRow(grid, "Last action", label, isError ? "fail" : "pass");
  if (isError) {
    addSummaryRow(grid, "Status", data.error || data.message || "Error", "fail");
    if (data.stage) {
      addSummaryRow(grid, "Stage", data.stage, "warn");
    }
    outputSummary.appendChild(grid);
    return;
  }

  if (label === "Job ready") {
    addSummaryRow(grid, "Status", "ready", "pass");
    addSummaryRow(grid, "Job ID", data.job_id);
    addSummaryRow(grid, "Job Type", data.job_type);
    addSummaryRow(grid, "Required views", data.required_views);
    addSummaryRow(grid, "Captured views", data.captured_views || []);
    addSummaryRow(grid, "Next action", data.next_action);
  } else if (label === "SKU found" || label === "SKU not found") {
    const metadata = metadataFromLookupResponse(data);
    const found = data.status === "found" || data.known;
    const prior = data.pot_prior || (metadata && metadata.pot_prior);
    addSummaryRow(grid, "Status", found ? "found" : "not found", found ? "pass" : "warn");
    addSummaryRow(grid, "SKU", data.sku || (metadata && metadata.sku));
    addSummaryRow(grid, "Quantity", field("quantity-input").value || "1");
    addSummaryRow(grid, "Common name", metadataCommonName(metadata));
    addSummaryRow(grid, "Description", metadata && metadata.description);
    addSummaryRow(grid, "Category", metadata && metadata.category);
    addSummaryRow(grid, "Spec", metadata && metadata.spec);
    addSummaryRow(grid, "UOM", metadata && metadata.uom);
    addSummaryRow(grid, "Pot prior", potPriorLabel(prior || metadata));
    addSummaryRow(grid, "Next action", found ? "Add item / Capture" : "enter manually or continue with warning");
    addSummaryRow(grid, "Required views", activeJob.required_views);
    addSummaryRow(grid, "Captured views", activeJob.captured_views);
  } else if (label === "Item added" || label === "Item removed") {
    const item = firstItemFromPayload(data) || activeJob.item_metadata || {};
    const metadata = item.metadata || {};
    addSummaryRow(grid, "Status", items.length ? "item ready" : "item removed", items.length ? "pass" : "warn");
    addSummaryRow(grid, "SKU", item.sku);
    addSummaryRow(grid, "Quantity", item.quantity);
    addSummaryRow(grid, "Known", metadata.known);
    addSummaryRow(grid, "Common name", metadataCommonName(metadata));
    addSummaryRow(grid, "Pot prior", potPriorLabel(metadata));
    addSummaryRow(grid, "Required views", activeJob.required_views);
    addSummaryRow(grid, "Captured views", activeJob.captured_views);
  } else if (label === "Capture complete") {
    const summary = data.quality_summary || (data.result && data.result.quality_summary) || {};
    const checks = summary.checks || {};
    const combinedFlags = data.result && data.result.combined_features && data.result.combined_features.quality_flags;
    addSummaryRow(grid, "Status", "capture complete", "pass");
    addSummaryRow(grid, "Capture view", data.current_view_id);
    addSummaryRow(grid, "Quality verdict", summary.status_label || summary.decision, summaryBadgeForStatus(summary.decision));
    addSummaryRow(grid, "Required views", data.required_views);
    addSummaryRow(grid, "Captured views", data.captured_views);
    addSummaryRow(grid, "Object status", checks.object && checks.object.status, summaryBadgeForStatus(checks.object && checks.object.status));
    addSummaryRow(grid, "Object cloud", checks.object_cloud && checks.object_cloud.status, summaryBadgeForStatus(checks.object_cloud && checks.object_cloud.status));
    addSummaryRow(grid, "Leaf/canopy status", checks.leaf && checks.leaf.status, summaryBadgeForStatus(checks.leaf && checks.leaf.status));
    addSummaryRow(grid, "Leaf cloud", checks.leaf_cloud && checks.leaf_cloud.status, summaryBadgeForStatus(checks.leaf_cloud && checks.leaf_cloud.status));
    addSummaryRow(grid, "Table status", checks.table && checks.table.status, summaryBadgeForStatus(checks.table && checks.table.status));
    addSummaryRow(grid, "Pot safety/source", (checks.pot && checks.pot.message) || (combinedFlags && combinedFlags.pot_source));
    addSummaryRow(grid, "features.json", checks.features && checks.features.status, summaryBadgeForStatus(checks.features && checks.features.status));
    addSummaryRow(grid, "combined_features.json", data.result && data.result.combined_features ? "present" : "missing", data.result && data.result.combined_features ? "pass" : "fail");
    addSummaryRow(grid, "Next action", data.next_action || activeJob.next_action);
  } else if (label === "Collected successfully — keep going") {
    addSummaryRow(grid, "Status", "saved", "pass");
    addSummaryRow(grid, "Job ID", data.ground_truth && data.ground_truth.job_id || activeJob.job_id);
    addSummaryRow(grid, "GT saved", data.ok === true, data.ok ? "pass" : "fail");
    addSummaryRow(grid, "Dataset sample complete", "yes", "pass");
    addSummaryRow(grid, "Next action", "start next sample");
  } else {
    addSummaryRow(grid, "Status", data.ok === false ? "error" : "ok", data.ok === false ? "fail" : "pass");
    addSummaryRow(grid, "Required views", activeJob.required_views);
    addSummaryRow(grid, "Captured views", activeJob.captured_views);
  }

  outputSummary.appendChild(grid);
}

function setSectionLocked(sectionId, locked) {
  const section = field(sectionId);
  section.classList.toggle("locked", locked);
  section.classList.toggle("active", !locked);
  section.querySelectorAll("input, select, textarea, button").forEach((control) => {
    control.disabled = locked;
  });
}

function renderWorkflow() {
  const hasJob = Boolean(activeJob.job_id);
  const hasSetup = setupPrepared || hasJob;
  const hasItem = items.length > 0;
  const capturesComplete = hasJob &&
    activeJob.required_views.length > 0 &&
    activeJob.remaining_views.length === 0;
  const captureUsable = activeJob.quality_verdict &&
    ["proceed", "review"].includes(activeJob.quality_verdict.decision) &&
    capturesComplete;

  setSectionLocked("itemSection", !hasSetup);
  if (!hasSetup) {
    field("sku-input").disabled = false;
    field("quantity-input").disabled = false;
    field("lookup-sku").disabled = false;
  }
  setSectionLocked("captureSection", !hasJob || !hasItem || captureInProgress);
  setSectionLocked("gtSection", !captureUsable);

  currentJobLabel.textContent = hasJob ? activeJob.job_id : "Not started";
  gtJobLabel.textContent = hasJob ? `Ground Truth for: ${activeJob.job_id}` : "Ground Truth for: pending capture";
  itemStatus.textContent = hasSetup ? (hasItem ? "Item added. Capture is ready." : "Add an item to unlock capture.") : "Locked until Job Setup is complete.";
  gtStatus.textContent = captureUsable ? "Ready for ground truth." : "Locked until capture is usable.";
  workflowStatus.textContent = workflowMessage(hasJob, hasItem, captureUsable);
  renderCaptureProgress(activeJob);
}

function workflowMessage(hasJob, hasItem, captureUsable) {
  if (!hasJob) {
    return setupPrepared ? "Add item metadata." : "Set up a job to begin.";
  }
  if (hasJob) {
    field("add-item").disabled = itemCommitInProgress;
  }
  if (!hasItem) {
    return "Add item metadata.";
  }
  if (captureInProgress) {
    return "Capture pipeline running.";
  }
  if (!activeJob.quality_verdict) {
    return "Ready to capture.";
  }
  if (captureUsable) {
    return "Capture usable. Enter ground truth.";
  }
  return "Recapture recommended.";
}

function resetQualitySummary() {
  qualitySummary.hidden = true;
  qualitySummary.className = "quality-card quality-waiting";
  qualityLabel.textContent = "Waiting for capture";
  qualityReasons.textContent = "";
  qualityChecks.textContent = "";
}

function checkLabel(key) {
  return {
    object: "Object",
    object_cloud: "Object Cloud",
    leaf: "Leaf",
    leaf_cloud: "Leaf Cloud",
    table: "Table",
    pot: "Pot",
    geometry: "Geometry",
    features: "Features",
    gt: "GT"
  }[key] || key;
}

function renderQualitySummary(summary) {
  if (!summary) {
    resetQualitySummary();
    return;
  }
  qualitySummary.hidden = false;
  qualitySummary.className = `quality-card quality-${summary.decision || "review"}`;
  qualityLabel.textContent = summary.status_label || "REVIEW";
  qualityReasons.textContent = "";

  const messages = [...(summary.reasons || []), ...(summary.warnings || [])].slice(0, 5);
  (messages.length ? messages : ["No blocking issues found."]).forEach((message) => {
    const item = document.createElement("li");
    item.textContent = message;
    qualityReasons.appendChild(item);
  });

  qualityChecks.textContent = "";
  const checks = summary.checks || {};
  ["object", "object_cloud", "leaf", "leaf_cloud", "table", "pot", "geometry", "features", "gt"].forEach((key) => {
    const check = checks[key] || {status: "warn", message: "Pending."};
    const pill = document.createElement("span");
    pill.className = `quality-check ${check.status || "warn"}`;
    pill.title = check.message || "";
    pill.textContent = `${checkLabel(key)}: ${(check.status || "warn").toUpperCase()}`;
    qualityChecks.appendChild(pill);
  });
}

function renderCaptureProgress(progress) {
  const required = progress.required_views || ["view_01"];
  const captured = progress.captured_views || [];
  const remaining = progress.remaining_views || required.filter((viewId) => !captured.includes(viewId));
  const nextAction = progress.next_action || nextActionForViews(required, captured, remaining);
  activeJob.required_views = required;
  activeJob.captured_views = captured;
  activeJob.remaining_views = remaining;

  viewCaptureStatus.textContent = [
    `Required views: ${required.join(", ")}`,
    `Captured: ${captured.length ? captured.join(", ") : "none"}`,
    remaining.length ? `Next: ${nextAction}` : "All captures completed. Ground Truth is ready."
  ].join(". ");
  captureStatus.textContent = remaining.length ? nextAction : "All captures completed. Ground Truth is ready.";

  const twoView = required.length > 1;
  const controlsLocked = captureInProgress || !activeJob.job_id || items.length === 0;
  const needsRecapture = activeJob.quality_verdict && activeJob.quality_verdict.decision === "recapture";
  recaptureButton.hidden = !needsRecapture;
  recaptureButton.disabled = controlsLocked || !needsRecapture;
  twoViewActions.hidden = !twoView;
  if (twoView) {
    const nextView = remaining[0] || null;
    field("collect").hidden = true;
    captureView01Button.hidden = nextView !== "view_01";
    captureView02Button.hidden = nextView !== "view_02";
    captureView01Button.disabled = controlsLocked || nextView !== "view_01";
    captureView02Button.disabled = controlsLocked || nextView !== "view_02";
  } else {
    field("collect").hidden = false;
    field("collect").textContent = remaining.length ? "Capture View 01" : "View 01 Complete";
    field("collect").disabled = controlsLocked || remaining.length === 0;
    captureView01Button.hidden = true;
    captureView02Button.hidden = true;
  }
}

function nextActionForViews(required, captured, remaining) {
  if (!remaining.length) {
    return "All captures completed. Ground Truth is ready.";
  }
  if (required.length > 1 && captured.includes("view_01") && remaining[0] === "view_02") {
    return "Rotate arrangement 90 degrees and capture View 02 / Width Side.";
  }
  return required.length > 1 ? "Capture View 01 / Front Side." : "Capture View 01.";
}

function normalizeSkuForCompare(sku) {
  return String(sku || "").trim().toUpperCase();
}

function metadataFromLookupResponse(response) {
  if (!response) {
    return response;
  }
  if (response.metadata) {
    return response.metadata;
  }
  if (response.item) {
    return response.item;
  }
  return response;
}

function draftMetadataFor(sku) {
  if (!lastLookup) {
    return null;
  }
  const metadata = metadataFromLookupResponse(lastLookup);
  if (!metadata || normalizeSkuForCompare(metadata.sku) !== normalizeSkuForCompare(sku)) {
    return null;
  }
  return metadata;
}

function readDraftItem() {
  const sku = field("sku-input").value.trim();
  const quantity = Number(field("quantity-input").value || 1);
  if (!sku) {
    throw {error: "Enter a SKU first."};
  }
  if (!Number.isInteger(quantity) || quantity <= 0) {
    throw {error: "Quantity must be a positive whole number."};
  }
  return {sku, quantity};
}

function knownLabel(item) {
  if (!item.metadata) {
    return "unchecked";
  }
  return item.metadata.known ? "known" : "unknown";
}

async function removeItem(index) {
  if (itemCommitInProgress) {
    return;
  }
  const nextItems = items.filter((_, itemIndex) => itemIndex !== index);
  try {
    itemCommitInProgress = true;
    renderWorkflow();
    if (backendJobCreated) {
      const response = await postJson("/api/job/remove-item", {
        job_type: activeJob.job_type,
        job_id: activeJob.job_id,
        items: nextItems.map((item) => ({
          sku: item.sku,
          quantity: item.quantity,
          allow_unresolved: item.allow_unresolved === true
        }))
      });
      if (response.deleted) {
        activeJob.job_id = "";
        activeJob.auto_generated_job_id = true;
        activeJob.capture_status = "pending";
        activeJob.quality_verdict = null;
        activeJob.current_view_id = null;
        activeJob.captured_views = [];
        activeJob.remaining_views = activeJob.required_views.slice();
        backendJobCreated = false;
        field("job-id").value = "";
        jobIdIsAutoGenerated = true;
        setupStatus.textContent = "Draft ready. Add an item to create the final Job ID.";
      }
      showStatus(response, response.deleted ? "Setup-only job removed" : "Item removed");
    }
    items = nextItems;
    activeJob.item_metadata = items[0] || null;
    renderItems();
  } catch (error) {
    showError(error, "Item removal blocked");
  } finally {
    itemCommitInProgress = false;
    renderWorkflow();
  }
}

function renderItems() {
  itemList.textContent = "";
  if (items.length === 0) {
    const row = document.createElement("tr");
    const cell = document.createElement("td");
    cell.colSpan = 4;
    cell.className = "empty-row";
    cell.textContent = "No item added yet.";
    row.appendChild(cell);
    itemList.appendChild(row);
    return;
  }

  items.forEach((item, index) => {
    const row = document.createElement("tr");
    [item.sku, String(item.quantity)].forEach((value) => {
      const cell = document.createElement("td");
      cell.textContent = value;
      row.appendChild(cell);
    });

    const knownCell = document.createElement("td");
    const pill = document.createElement("span");
    pill.className = `mini-pill ${knownLabel(item)}`;
    pill.textContent = knownLabel(item);
    knownCell.appendChild(pill);
    row.appendChild(knownCell);

    const actionCell = document.createElement("td");
    const removeButton = document.createElement("button");
    removeButton.type = "button";
    removeButton.className = "danger outline";
    removeButton.textContent = "Remove";
    removeButton.addEventListener("click", () => removeItem(index));
    actionCell.appendChild(removeButton);
    row.appendChild(actionCell);
    itemList.appendChild(row);
  });
}

async function prepareJob() {
  try {
    if (!field("job-id").value.trim() || jobIdIsAutoGenerated) {
      refreshAutoJobId({force: true});
    }
    const payload = {
      job_type: field("job-type").value,
      job_id: jobIdIsAutoGenerated ? null : (field("job-id").value.trim() || null),
      arrangement_type: field("arrangement-type").value.trim() || "1x1",
      items: jobSetupItems()
    };
    const response = await postJson("/api/job/setup", payload);
    activeJob = {
      ...activeJob,
      job_id: response.job_id,
      auto_generated_job_id: Boolean(response.auto_generated_job_id),
      job_type: response.job_type,
      operator_id: field("operator-id").value.trim() || null,
      arrangement_type: response.arrangement_type,
      capture_status: "pending",
      quality_verdict: null,
      current_view_id: null,
      gt_status: "pending",
      required_views: response.required_views || ["view_01"],
      captured_views: [],
      remaining_views: response.remaining_views || response.required_views || ["view_01"]
    };
    backendJobCreated = false;
    setupPrepared = true;
    activeJob.next_action = response.next_action || nextActionForViews(
      activeJob.required_views,
      activeJob.captured_views,
      activeJob.remaining_views
    );
    field("job-id").value = response.job_id;
    jobIdIsAutoGenerated = Boolean(response.auto_generated_job_id);
    setupStatus.textContent = `Current Job: ${response.job_id}`;
    resetQualitySummary();
    renderWorkflow();
    showStatus(response, "Job ready");
  } catch (error) {
    setupStatus.textContent = error.error || "Job setup failed.";
    showError(error, "Job setup failed");
  }
}

async function lookupSku() {
  try {
    const draft = readDraftItem();
    const response = await postJson("/api/sku/lookup", {sku: draft.sku});
    lastLookup = response;
    refreshAutoJobId();
    showStatus(response, response.known ? "SKU found" : "SKU not found");
  } catch (error) {
    showError(error, "SKU lookup failed");
  }
}

async function addItem() {
  if (itemCommitInProgress) {
    return;
  }
  try {
    itemCommitInProgress = true;
    renderWorkflow();
    const nextItem = readDraftItem();
    const metadata = draftMetadataFor(nextItem.sku);
    const allowUnresolved = field("allow-unresolved-sku").checked;
    if (metadata && metadata.known === true) {
      nextItem.metadata = metadata;
    } else if (allowUnresolved) {
      nextItem.metadata = metadata || {sku: nextItem.sku, known: false, lookup_status: "operator_approved_unresolved"};
      nextItem.allow_unresolved = true;
    } else if (metadata && metadata.known === false) {
      throw {error: "SKU not found"};
    } else {
      throw {error: "Lookup SKU before adding the item."};
    }
    const nextItems = items.map((item) => ({...item}));
    const existing = nextItems.find(
      (item) => normalizeSkuForCompare(item.sku) === normalizeSkuForCompare(nextItem.sku)
    );
    if (existing) {
      existing.quantity += nextItem.quantity;
      existing.metadata = nextItem.metadata || existing.metadata;
      existing.allow_unresolved = nextItem.allow_unresolved === true || existing.allow_unresolved === true;
    } else {
      nextItems.push(nextItem);
    }
    const response = await postJson("/api/job/commit-items", {
      job_type: activeJob.job_type,
      job_id: backendJobCreated || !activeJob.auto_generated_job_id ? activeJob.job_id : null,
      arrangement_type: activeJob.arrangement_type,
      operator_id: activeJob.operator_id,
      items: nextItems.map((item) => ({
        sku: item.sku,
        quantity: item.quantity,
        allow_unresolved: item.allow_unresolved === true
      }))
    });
    items = nextItems;
    activeJob.job_id = response.job_id;
    activeJob.auto_generated_job_id = false;
    activeJob.required_views = response.required_views || activeJob.required_views;
    activeJob.remaining_views = activeJob.required_views.filter(
      (viewId) => !activeJob.captured_views.includes(viewId)
    );
    backendJobCreated = true;
    field("job-id").value = response.job_id;
    jobIdIsAutoGenerated = false;
    setupStatus.textContent = `Current Job: ${response.job_id}`;
    activeJob.item_metadata = items[0] || null;
    field("sku-input").value = "";
    field("quantity-input").value = "1";
    field("allow-unresolved-sku").checked = false;
    renderItems();
    renderWorkflow();
    showStatus(response, response.created ? "Job created; item added" : "Item added");
  } catch (error) {
    showError(error, "Item error");
  } finally {
    itemCommitInProgress = false;
    renderWorkflow();
  }
}

async function captureCollect(viewId = null, options = {}) {
  try {
    if (!backendJobCreated) {
      throw {error: "Add the first item to create the dataset job before capture."};
    }
    captureInProgress = true;
    renderWorkflow();
    const nextView = activeJob.remaining_views && activeJob.remaining_views[0];
    captureStatus.textContent = viewId
      ? `Capturing ${viewId}...`
      : (nextView ? `Capturing ${nextView}...` : "Collecting data...");

    const payload = {
      mode: "data_collection",
      job_type: activeJob.job_type,
      job_id: activeJob.job_id,
      arrangement_type: activeJob.arrangement_type,
      operator_id: activeJob.operator_id,
      debug_mode: field("debug-mode").checked,
      save_object_cloud: field("save-object-cloud").checked,
      items: items.map((item) => ({
        sku: item.sku,
        quantity: item.quantity,
        allow_unresolved: item.allow_unresolved === true
      }))
    };
    if (viewId) {
      payload.view_id = viewId;
    }
    if (options.overwrite) {
      payload.overwrite = true;
    }
    const response = await postJson("/api/collect", payload);
    activeJob.job_id = response.job_id;
    activeJob.auto_generated_job_id = false;
    activeJob.current_view_id = response.current_view_id || viewId || activeJob.current_view_id;
    activeJob.capture_status = "complete";
    activeJob.quality_verdict = response.quality_summary || (response.result && response.result.quality_summary) || null;
    activeJob.captured_views = response.captured_views || [];
    activeJob.required_views = response.required_views || activeJob.required_views;
    activeJob.remaining_views = response.remaining_views || [];
    activeJob.next_action = response.next_action || nextActionForViews(
      activeJob.required_views,
      activeJob.captured_views,
      activeJob.remaining_views
    );
    renderQualitySummary(activeJob.quality_verdict);
    captureStatus.textContent = activeJob.quality_verdict
      ? activeJob.quality_verdict.status_label
      : (response.next_action || "Capture complete.");
    showStatus(response, "Capture complete");
  } catch (error) {
    captureStatus.textContent = error.error ? `Capture failed: ${error.error}` : "Capture failed.";
    showError(error, "Capture failed");
  } finally {
    captureInProgress = false;
    renderWorkflow();
  }
}

async function recaptureSelectedView() {
  const viewId = activeJob.current_view_id || activeJob.captured_views[activeJob.captured_views.length - 1] || "view_01";
  await captureCollect(viewId, {overwrite: true});
}

function buildGroundTruthPayload() {
  if (!activeJob.job_id) {
    throw {error: "No active job."};
  }
  const missing = [];
  const invalid = [];
  const fit = field("gt-fit").value.trim();
  const payload = {
    job_type: activeJob.job_type,
    job_id: activeJob.job_id,
    source: "manual",
    fit,
    damage: field("gt-damage").checked
  };
  if (!fit) {
    missing.push("fit");
  }
  [
    ["gt-length", "length", "length_in"],
    ["gt-width", "width", "width_in"],
    ["gt-height", "height", "height_in"]
  ].forEach(([fieldId, label, payloadKey]) => {
    const rawValue = field(fieldId).value.trim();
    if (!rawValue) {
      missing.push(label);
      return;
    }
    const value = Number(rawValue);
    if (!Number.isFinite(value) || value <= 0) {
      invalid.push(label);
      return;
    }
    payload[payloadKey] = value;
  });
  const notes = field("gt-notes").value.trim();
  if (notes) {
    payload.notes = notes;
  }
  if (missing.length > 0) {
    throw {error: `Ground truth missing: ${missing.join(", ")}`};
  }
  if (invalid.length > 0) {
    throw {error: `Ground truth invalid: ${invalid.join(", ")} must be positive numbers`};
  }
  return payload;
}

